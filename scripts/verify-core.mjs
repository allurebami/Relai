import assert from "node:assert/strict";
import {readFile,writeFile,mkdir} from "node:fs/promises";
import "fake-indexeddb/auto";
import ts from "typescript";

const compile=async path=>ts.transpileModule(await readFile(path,"utf8"),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const url=code=>"data:text/javascript;base64,"+Buffer.from(code).toString("base64");
const typeUrl=url(await compile("app/types.ts"));
const types=await import(typeUrl);
const schemaUrl=url((await compile("lib/studio-schema.ts")).replace('"zod"',JSON.stringify(import.meta.resolve("zod"))));
const storageUrl=url((await compile("lib/local-studio.ts")).replace('"../app/types"',JSON.stringify(typeUrl)).replace('"./studio-schema"',JSON.stringify(schemaUrl)));
const storage=await import(storageUrl);
const media=await import(url((await compile("app/media-utils.ts")).replace('"./types"',JSON.stringify(typeUrl)).replace('"../lib/local-studio"',JSON.stringify(storageUrl))));
const content={id:types.newId(),title:"Un projet, une idée ; et des élèves",notes:"Ligne 1\nLigne 2",kind:"text",brand:"SIU",createdAt:"2026-10-25T05:00:00.000Z"};
let studio={...types.emptyStudio,contents:[content]};
studio=types.prepareDrafts(studio,content,[...types.platforms]);
assert.equal(studio.drafts.length,5);
assert.equal(new Set(studio.drafts.map(d=>d.id)).size,5);
studio.drafts[0].caption="Texte personnalisé à préserver.";
const again=types.prepareDrafts(studio,content,[...types.platforms]);
assert.equal(again.drafts.length,5,"Applying twice must not create duplicate posts");
assert.equal(again.drafts[0].caption,studio.drafts[0].caption,"Applying twice must preserve edits");
assert.equal(types.captionFor({...content,notes:"x".repeat(10000)},"instagram","").length,2150);
const draft={...studio.drafts[0],scheduledAt:"2026-10-30T14:00:00.000Z",status:"scheduled"};
const ics=await media.calendarFile([draft],[content]).text();
assert.ok(ics.includes("DTSTART:20261030T140000Z"));
assert.ok(ics.includes("Un projet\\, une idée \\; et des élèves"));
assert.ok(ics.includes("Publication manuelle prévue."));
for(const line of ics.split("\r\n"))assert.ok(Buffer.byteLength(line)<=75);
await mkdir(".relai-test",{recursive:true});
await writeFile(".relai-test/core-test.zip",Buffer.from(await(await media.contentPack(content,[draft])).arrayBuffer()));
console.log("Core verification passed: destinations, duplicate prevention, edit preservation, caption limits and UTC calendar.");

const initial=await(await storage.requestStudio("/api/studio")).json();
assert.equal(initial.version,0);
const save=(state,version)=>storage.requestStudio("/api/studio",{method:"PUT",body:JSON.stringify({state,version})});
const results=await Promise.all([save(studio,0),save({...studio,workspace:"Autre onglet"},0)]);
assert.deepEqual(results.map(r=>r.status).sort(),[200,409],"Concurrent writes must reject the stale version.");
const saved=await(await storage.requestStudio("/api/studio")).json();
assert.equal(saved.version,1);
assert.equal(saved.state.contents[0].title,content.title);
const reloaded=await import(storageUrl+"#reloaded");
const reopened=await(await reloaded.requestStudio("/api/studio")).json();
assert.deepEqual(reopened,saved,"Reopening the database must preserve state.");
const invalid=await save({...studio,drafts:[{...studio.drafts[0],contentId:types.newId()}]},1);
assert.equal(invalid.status,400);
assert.equal((await(await storage.requestStudio("/api/studio")).json()).version,1);
const form=new FormData();form.append("file",new File(["binary fixture"],"image.jpg",{type:"image/jpeg"}));
const upload=await storage.requestStudio("/api/upload",{method:"POST",body:form});
assert.equal(upload.status,200);
const file=await upload.json();
const returned=await storage.requestStudio("/api/media/"+file.fileId);
assert.equal(returned.headers.get("content-type"),"image/jpeg");
assert.equal(await returned.text(),"binary fixture");
assert.equal((await storage.localMedia(file.fileId)).fileName,"image.jpg");
const invalidForm=new FormData();invalidForm.append("file",new File(["<script>"],"bad.html",{type:"text/html"}));
assert.equal((await storage.requestStudio("/api/upload",{method:"POST",body:invalidForm})).status,400);
assert.equal((await storage.requestStudio("/api/media/"+file.fileId,{method:"DELETE"})).status,200);
assert.equal((await storage.requestStudio("/api/media/"+file.fileId)).status,404);
console.log("IndexedDB verification passed: persistence, atomic concurrent saves, validation, binary media import/read/delete and invalid-file rejection.");
